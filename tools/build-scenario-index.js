// Builds site/scenario-index.js: a small index of the playground's scenarios
// (id, title, group, level, story) and the number of quiz questions, so the
// first screen (the stats, the path's practise links and the on-call shift)
// can be drawn before the engine, the scenarios and the quiz bank have loaded.
// Run with: node tools/build-scenario-index.js   (tests/check_playground.js keeps it in sync)
"use strict";
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const file = path.join(root, "site/scenario-index.js");

function render() {
  const fresh = (f) => { const p = path.join(root, "site", f); delete require.cache[p]; require(p); };
  if (!globalThis.window) globalThis.window = {};
  for (const f of ["yaml.js", "engine.js", "scenarios.js", "quiz-bank.js"]) fresh(f);
  const pick = (k) => globalThis.window[k] || globalThis[k];
  const list = pick("AQScenarios").SCENARIOS.map((s) => ({ id: s.id, title: s.title, group: s.group, level: s.level, story: s.story }));
  const quiz = Object.values(pick("TRACK_QUIZ_BANK")).flat().length;
  return `// Generated by tools/build-scenario-index.js from site/scenarios.js and site/quiz-bank.js. Do not edit.
"use strict";
window.TRACK_QUIZ_COUNT = ${quiz};
window.TRACK_SCENARIOS = ${JSON.stringify(list, null, 1)};
`;
}

if (require.main === module) {
  fs.writeFileSync(file, render());
  console.log(`wrote ${path.relative(root, file)}`);
}
module.exports = { render, file };
